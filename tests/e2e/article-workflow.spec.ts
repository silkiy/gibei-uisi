import { test, expect } from './fixtures';
import type { Page } from '@playwright/test';

test('Admin, two Media and visitor complete the article lifecycle through CMS and public pages', async ({ adminPage, mediaAPage, mediaBPage, page, baseURL }) => {
  test.setTimeout(120000);
  adminPage.setDefaultTimeout(10000); mediaAPage.setDefaultTimeout(10000);
  const headers = { Origin: baseURL! };
  const category = await adminPage.request.post('/api/article-categories', { headers, data: { name: 'Workflow Demo', slug: 'workflow-demo' } }); expect(category.status()).toBe(201);
  await mediaAPage.goto('/admin/collections/articles/create');
  await mediaAPage.getByLabel(/^Slug/).fill('workflow-browser');
  await mediaAPage.getByLabel(/^Title/).fill('Artikel alur lengkap contoh');
  await mediaAPage.getByLabel(/^Excerpt/).fill('Ringkasan alur editorial untuk demonstrasi.');
  await mediaAPage.getByLabel(/^Public Author/).fill('Tim Edukasi Contoh');
  await mediaAPage.locator('[contenteditable="true"]').fill('Isi draft pertama untuk review.');
  await mediaAPage.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(mediaAPage).toHaveURL(/\/admin\/collections\/articles\/\d+$/);
  const id = Number(mediaAPage.url().split('/').at(-1)), editor = `/admin/collections/articles/${id}`, publicURL = '/publikasi/artikel/workflow-browser';
  expect(Number.isSafeInteger(id)).toBe(true);
  async function save(actor: Page) {
    const result = actor.waitForResponse(response => response.url().includes(`/api/articles/${id}`) && response.request().method() === 'PATCH');
    await actor.getByRole('button', { name: 'Save', exact: true }).click(); expect((await result).status()).toBe(200);
  }
  const read = async (actor: Page) => (await actor.request.get(`/api/articles/${id}`, { headers })).json();
  expect((await page.request.get(publicURL)).status()).toBe(404);
  expect((await mediaBPage.request.get(`/api/articles/${id}`, { headers })).status()).toBe(404);
  expect((await adminPage.request.get(`/api/articles/${id}`, { headers })).status()).toBe(200);
  await adminPage.goto(editor);
  await expect(adminPage).toHaveURL(new RegExp(`/admin/collections/articles/${id}$`));
  await expect(adminPage.getByRole('heading', { name: 'Alur editorial', exact: true })).toBeVisible();
  await adminPage.locator('#field-category').getByRole('combobox').fill('Workflow Demo');
  await adminPage.getByRole('option', { name: 'Workflow Demo', exact: true }).click();
  await save(adminPage);
  await mediaAPage.reload(); await mediaAPage.getByRole('button', { name: 'Ajukan review', exact: true }).click();
  await expect(mediaAPage.getByText('Status editorial: in_review', { exact: true })).toBeVisible();
  await adminPage.goto('/admin/collections/articles');
  await adminPage.getByRole('link', { name: 'Tinjau: Artikel alur lengkap contoh', exact: true }).click();
  await adminPage.getByRole('link', { name: 'Preview privat', exact: true }).click();
  await expect(adminPage.getByText('Isi draft pertama untuk review.', { exact: true })).toBeVisible();
  await adminPage.goto(editor);
  await adminPage.getByLabel('Alasan editorial').fill('Perjelas sumber dan konteks pembelajaran.');
  await adminPage.getByRole('button', { name: 'Minta revisi', exact: true }).click();
  await expect(adminPage.getByText('Status editorial: revision_required', { exact: true })).toBeVisible();
  await mediaAPage.reload(); await expect(mediaAPage.getByText('Perjelas sumber dan konteks pembelajaran.', { exact: true })).toBeVisible();
  await mediaAPage.getByLabel(/^Title/).fill('Artikel alur lengkap diperbaiki');
  await mediaAPage.locator('[contenteditable="true"]').fill('Isi diperbaiki dengan konteks edukasi yang jelas.');
  await save(mediaAPage);
  await mediaAPage.getByRole('button', { name: 'Ajukan review', exact: true }).click();
  await expect(mediaAPage.getByText('Status editorial: in_review', { exact: true })).toBeVisible();
  await adminPage.goto('/admin/collections/articles'); await adminPage.getByRole('link', { name: 'Tinjau: Artikel alur lengkap diperbaiki', exact: true }).click();
  await adminPage.getByRole('button', { name: 'Terbitkan', exact: true }).click();
  await expect(adminPage.getByText('Status editorial: published', { exact: true })).toBeVisible();
  await page.goto(publicURL); await expect(page.getByRole('heading', { name: 'Artikel alur lengkap diperbaiki', exact: true })).toBeVisible();
  await expect(page.getByText('Isi diperbaiki dengan konteks edukasi yang jelas.', { exact: true })).toBeVisible();
  await mediaAPage.reload(); await mediaAPage.getByRole('button', { name: 'Buat revisi baru', exact: true }).click();
  await expect(mediaAPage.getByText('Status editorial: draft', { exact: true })).toBeVisible();
  await mediaAPage.getByLabel(/^Title/).fill('Judul revisi yang masih privat');
  await mediaAPage.locator('[contenteditable="true"]').fill('Isi revisi rahasia sebelum persetujuan berikutnya.');
  await save(mediaAPage);
  await page.reload(); await expect(page.getByRole('heading', { name: 'Artikel alur lengkap diperbaiki', exact: true })).toBeVisible();
  await expect(page.locator('main')).not.toContainText('Isi revisi rahasia');
  await mediaAPage.getByRole('button', { name: 'Ajukan review', exact: true }).click();
  await expect(mediaAPage.getByText('Status editorial: in_review', { exact: true })).toBeVisible();
  await adminPage.goto(editor); await adminPage.getByLabel('Alasan editorial').fill('Tarik publikasi untuk peninjauan lebih lanjut.');
  await adminPage.getByRole('button', { name: 'Tarik publikasi', exact: true }).click();
  await expect(adminPage.getByText('Status editorial: draft', { exact: true })).toBeVisible();
  const withdrawn = await page.reload(); expect(withdrawn!.status()).toBe(404);
  await expect(page.getByRole('heading', { name: 'Artikel tidak tersedia.', exact: true })).toBeVisible();
  await page.goto('/publikasi/artikel?q=Artikel%20alur%20lengkap'); await expect(page.getByRole('status').filter({ hasText: /^0 artikel/ })).toBeVisible();
  await mediaAPage.reload(); await expect(mediaAPage.getByLabel(/^Title/)).toHaveValue('Judul revisi yang masih privat');
  const doc = await read(adminPage);
  const reviews = await (await adminPage.request.get(`/api/content-reviews?where[article][equals]=${id}&sort=-createdAt&limit=1`, { headers })).json();
  expect(reviews.docs[0].status).toBe('cancelled');
  const stale = await adminPage.request.post(`/api/editorial/articles/${id}/publish`, { headers, data: { expectedLockVersion: doc.lockVersion, expectedRevisionId: doc.workingRevision, submissionId: reviews.docs[0].id } }); expect(stale.status()).toBe(409);
  const audit = await (await adminPage.request.get(`/api/editorial-audit?where[article][equals]=${id}&limit=100`, { headers })).json();
  for (const action of ['draft_created', 'submitted', 'revision_requested', 'published', 'revision_created', 'publication_withdrawn']) expect(audit.docs.some((row: { action: string }) => row.action === action)).toBe(true);
});
